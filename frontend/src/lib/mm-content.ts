// Look up Burmese content for a record using any identifying field
// (id, _id, slug, title, name, planName, carType, city, country — raw or slugified).
export function mmLookup<T>(map: Record<string, Partial<T>>, item: any): Partial<T> {
  if (!item) return {};
  const fields = ["id", "_id", "slug", "title", "name", "planName", "carType", "city", "country"];
  const keys: string[] = [];
  for (const f of fields) {
    const v = item[f];
    if (v === undefined || v === null || v === "") continue;
    keys.push(String(v));
    keys.push(String(v).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""));
  }
  for (const k of keys) {
    if (map[k]) return map[k];
  }
  return {};
}

